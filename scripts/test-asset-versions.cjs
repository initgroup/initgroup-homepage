const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const fixture=fs.mkdtempSync(path.join(root,'.tmp','version-test-'));
const write=(file,text)=>{const target=path.join(fixture,file);fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,text);};
const read=file=>fs.readFileSync(path.join(fixture,file),'utf8');
const manifest=['index.html','company/index.html','assets/js/common.js','assets/js/site.js','assets/css/site.css','assets/images/sample.png','assets/shared/site.json','assets/shared/layout.html'];
write('static-files.json',JSON.stringify(manifest));
write('assets/shared/site.json',JSON.stringify({components:'assets/shared/layout.html'},null,2)+'\n');
write('assets/shared/layout.html','<template id="footer">Fixture footer</template>');
write('assets/js/common.js','window.fixtureCommon=1;\n');
write('assets/js/site.js','window.fixtureSite=1;\n');
write('assets/css/site.css','body{background:url("../images/sample.png?size=2#detail")}\n');
write('assets/images/sample.png','fixture-image-one');
for(const file of ['index.html','company/index.html'])write(file,'<head><script src="'+(file==='index.html'?'':'../')+'assets/js/common.js" data-page-file="'+file+'"></script></head><main>Authored body</main>');
write('scripts/update-asset-versions.ps1',fs.readFileSync(path.join(root,'scripts/update-asset-versions.ps1')));
const run=(check=false)=>execFileSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(fixture,'scripts/update-asset-versions.ps1'),...(check?['-Check']:[])],{cwd:os.tmpdir(),encoding:'utf8',windowsHide:true,stdio:['ignore','pipe','pipe']});
const versions=()=>JSON.parse(read('assets/shared/site.json')).assetVersions;
const snapshot=()=>Object.fromEntries(manifest.map(file=>[file,{content:read(file),mtime:fs.statSync(path.join(fixture,file)).mtimeMs}]));
run();
const first=versions(), firstSnapshot=snapshot(), firstHtml=read('index.html');
assert.match(read('assets/css/site.css'),/\?size=2&v=[a-f0-9]{16}#detail/);
assert.match(firstHtml,/common\.js\?v=[a-f0-9]{16}/);
assert.match(run(),/0 file\(s\) updated/);
assert.deepEqual(snapshot(),firstSnapshot,'Unchanged preparation must not rewrite files or change timestamps');
run(true);
write('assets/js/site.js',read('assets/js/site.js'));
run();
assert.deepEqual(versions(),first,'Mtime alone must not change a version');
write('assets/js/site.js','window.fixtureSite=2;\n');
assert.throws(()=>run(true),/Asset versions are stale/);
run();
const afterJs=versions();
assert.notEqual(afterJs['assets/js/site.js'],first['assets/js/site.js']);
for(const file of Object.keys(first).filter(file=>file!=='assets/js/site.js'))assert.equal(afterJs[file],first[file],file+' changed unnecessarily');
assert.equal(read('index.html'),firstHtml,'A leaf script change must not rewrite every HTML');
write('assets/images/sample.png','fixture-image-two');
run();
const afterImage=versions();
assert.notEqual(afterImage['assets/images/sample.png'],afterJs['assets/images/sample.png']);
assert.notEqual(afterImage['assets/css/site.css'],afterJs['assets/css/site.css'],'CSS dependency must invalidate the containing stylesheet');
assert.equal(afterImage['assets/js/site.js'],afterJs['assets/js/site.js']);
write('assets/js/common.js','window.fixtureCommon=2;\n');
run();
assert.notEqual(read('index.html'),firstHtml,'Bootstrap content changes must update its HTML reference');
assert.match(read('company/index.html'),new RegExp('common\\.js\\?v='+versions()['assets/js/common.js']));
assert.ok(read('company/index.html').endsWith('<main>Authored body</main>'),'Authored body must remain untouched');
assert.match(run(),/0 file\(s\) updated/);
run(true);
console.log('PASS: content-only per-file versions; repeated packaging is byte/mtime stable; same-content saves do not bump versions; JS changes stay local; image/font dependencies invalidate CSS; bootstrap references update without rewriting bodies; script works outside project cwd.');